"""Build data/mods/late_pairs.json: building-mod pieces -> the base-game piece they copy.

Used only by the plugin's /aplatemod (a building mod installed AFTER the seed was generated). The
plugin already pairs "<X> Plus" / " Tek" / " SS" / " SP" / " LR" engrams with base X the same way
the apworld's _variant_pairs does. That misses the mod's material building pieces, which S+ names
material-LAST ("Ceiling Stone") while our base-game names come from ARK's class names, material
first ("Stone Ceiling"), and sometimes under the internal name ("Foundation" is StoneFloor).

A mod piece is paired when, after the renames below, its words are exactly the words of ONE
base-game structure. Anything ambiguous or with no base twin is left out (it stays locked) and
listed by this script. Pieces the suffix rule already pairs are skipped (the plugin does those).

Run after changing a mod catalogue or engrams.json:
    python tools/gen_late_pairs.py
"""
import ast
import json
import os
import re
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIRS = [os.path.join(ROOT, "data", "mods"), os.path.join(ROOT, "apworld", "ark_ase", "data", "mods")]
MATERIALS = ["Wood", "Stone", "Metal", "Greenhouse", "Tek", "Thatch", "Adobe"]
# mod word -> the base-game ap_name word for the same piece. ARK's class names (which our base
# ap_names come from) differ from the in-game names for these.
RENAMES = [
    ("Window Wall", "Wall With Window"),        # Windowframe   = <Mat>WallWithWindow
    ("Doorframe", "Wall With Door"),            # Doorframe     = <Mat>WallWithDoor
    ("Hatchframe", "Ceiling With Trapdoor"),    # Hatchframe    = <Mat>CeilingWithTrapdoor
    ("Foundation", "Floor"),                    # Foundation    = <Mat>Floor
    ("Staircase", "Stairs"),                    # Staircase     = <Mat>Stairs
    ("Gateway", "Gategrame"),                   # Tek Gateway: our base name keeps ARK's typo
]
# Every size of a material pillar copies the one base pillar of that material: owning "Wood Pillar"
# unlocks Small/Medium/Large/Dynamic Pillar Wood (Justin's call, 2026-11-11). Applied before the
# word match, so "Large Pillar Stone" -> "Pillar Stone" -> base "Stone Pillar".
PILLAR_SIZES = re.compile(r"^(?:Small|Medium|Large|Dynamic) (?=Pillar )")
# Mods to build a table for (the building mods; utility mods have no material pieces).
MODS = ["731604991"]


def load(path):
    return json.load(open(path, encoding="utf-8"))


def apworld_variant_rules():
    """VARIANT_ALIAS / VARIANT_SUFFIXES straight from the apworld source, so the skip set matches."""
    tree = ast.parse(open(os.path.join(ROOT, "apworld", "ark_ase", "__init__.py"), encoding="utf-8").read())
    got = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            if node.targets[0].id in ("VARIANT_ALIAS", "VARIANT_SUFFIXES"):
                got[node.targets[0].id] = ast.literal_eval(node.value)
    return got["VARIANT_ALIAS"], got["VARIANT_SUFFIXES"]


def main():
    alias, suffixes = apworld_variant_rules()
    eng = load(os.path.join(ROOT, "data", "engrams.json"))
    eng = eng["engrams"] if isinstance(eng, dict) else eng
    vanilla = {e["ap_name"]: e for e in eng}

    def suffix_base(nm):                       # the plugin's / apworld's own variant rule
        if nm in alias:
            return alias[nm]
        for s in suffixes:
            if nm.endswith(s):
                return nm[: -len(s)]
        if " Plus " in nm:
            return nm.replace(" Plus ", " ", 1)
        return None

    def words(n):
        return frozenset(w.lower() for w in re.findall(r"[A-Za-z0-9]+", n.replace("Engram: ", "")))

    def has_word(n, w):
        return re.search(r"(?<![A-Za-z0-9])" + w + r"(?![A-Za-z0-9])", n) is not None

    by_words = defaultdict(list)
    for n, e in vanilla.items():
        if "PrimalItemStructure_" in e.get("engram_class", ""):
            by_words[words(n)].append(n)

    out = {"_comment": [
        "Generated by tools/gen_late_pairs.py - do not hand-edit. Plugin-only (/aplatemod).",
        "mod id -> {mod engram item id: base-game engram item id}. The mod piece unlocks when the",
        "slot owns the base piece. Only exact word matches (after the renames in the script).",
    ]}
    for mod_id in MODS:
        mod = load(os.path.join(ROOT, "data", "mods", "%s.json" % mod_id))
        pairs, locked = {}, []
        for e in mod["engrams"]:
            vs = e.get("variants") or []
            nm = e["ap_name"]
            b = suffix_base(nm)
            if b and b != nm and b in vanilla:
                continue                                    # suffix rule already pairs it
            if "PrimalItemStructure_" not in e.get("engram_class", ""):
                continue
            if not any(has_word(nm, m) for m in MATERIALS):
                continue                                    # not a material building piece
            s = re.sub(r"\s*\([^)]*\)$", "", nm.replace("Engram: ", ""))   # "(StructuresPl)" tag
            s = PILLAR_SIZES.sub("", s)
            hits = by_words.get(words(s), [])
            if not hits:
                r = s
                for a, bb in RENAMES:
                    r = re.sub(r"(?<![A-Za-z])" + a + r"(?![A-Za-z])", bb, r)
                if r != s:
                    hits = by_words.get(words(r), [])
            if len(hits) == 1:
                pairs[str(e["id"])] = vanilla[hits[0]]["id"]
                print("  pair  %-36s -> %s%s" % (nm.replace("Engram: ", ""), hits[0].replace("Engram: ", ""),
                                                 "" if not vs else "  (forks: %s)" % ",".join(vs)))
            else:
                locked.append(nm.replace("Engram: ", "") + (" [ambiguous: %d]" % len(hits) if hits else ""))
        out[mod_id] = pairs
        print("%s: %d pairs, %d material pieces with no single base twin (stay locked):"
              % (mod_id, len(pairs), len(locked)))
        print("  " + ", ".join(locked))
    for d in OUT_DIRS:
        with open(os.path.join(d, "late_pairs.json"), "w", encoding="utf-8", newline="\n") as fh:
            json.dump(out, fh, indent=1)
            fh.write("\n")
    print("wrote late_pairs.json to data/mods and apworld/ark_ase/data/mods")


if __name__ == "__main__":
    main()
